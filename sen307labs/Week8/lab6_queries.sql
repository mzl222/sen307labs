-- Task 1: Count students enrolled in each course (including 0)
-- ============================================================
SELECT c.course_code, c.course_title, COUNT(e.student_id) AS total_students
FROM Course c
LEFT JOIN Enrolment e ON c.course_id = e.course_id
GROUP BY c.course_id, c.course_title
ORDER BY total_students DESC;
-- Explanation: Uses LEFT JOIN from Course to Enrolment and groups by course to count enrolled students, ordered from highest to lowest. COUNT(e.student_id) returns 0 rather than 1 for empty courses because COUNT(column) ignores NULL values generated by the LEFT JOIN, whereas COUNT(*) would count the unmatched row itself.

-- ============================================================
-- Task 2: Courses with more than 3, 5, and 7 students (HAVING)
-- ============================================================
-- Threshold > 3
SELECT c.course_code, c.course_title, COUNT(e.student_id) AS total_students
FROM Course c
LEFT JOIN Enrolment e ON c.course_id = e.course_id
GROUP BY c.course_id, c.course_title
HAVING COUNT(e.student_id) > 3
ORDER BY total_students DESC;

-- Threshold > 5
SELECT c.course_code, c.course_title, COUNT(e.student_id) AS total_students
FROM Course c
LEFT JOIN Enrolment e ON c.course_id = e.course_id
GROUP BY c.course_id, c.course_title
HAVING COUNT(e.student_id) > 5
ORDER BY total_students DESC;

-- Threshold > 7
SELECT c.course_code, c.course_title, COUNT(e.student_id) AS total_students
FROM Course c
LEFT JOIN Enrolment e ON c.course_id = e.course_id
GROUP BY c.course_id, c.course_title
HAVING COUNT(e.student_id) > 7
ORDER BY total_students DESC;
-- Explanation: Uses HAVING after GROUP BY to filter aggregated course enrolment counts using thresholds of 3, 5, and 7. WHERE cannot be used here because aggregate functions like COUNT() are evaluated only after rows are grouped.

-- ============================================================
-- Task 3: Average number of courses taken per student
-- ============================================================
SELECT ROUND(AVG(course_count), 2) AS avg_courses_per_student
FROM (
    SELECT s.student_id, COUNT(e.course_id) AS course_count
    FROM Student s
    LEFT JOIN Enrolment e ON s.student_id = e.student_id
    GROUP BY s.student_id
) AS per_student;
-- Explanation: The inner derived table (per_student) uses a LEFT JOIN so students with zero enrolments are included with a course_count of 0. The outer query then computes the overall mean across all students rounded to 2 decimal places.

-- ============================================================
-- Task 4: Students not enrolled in any course (Non-correlated subquery)
-- ============================================================
SELECT matric_no, full_name
FROM Student
WHERE student_id NOT IN (
    SELECT DISTINCT student_id
    FROM Enrolment
    WHERE student_id IS NOT NULL
)
ORDER BY full_name ASC;
-- Explanation: A non-correlated subquery fetches the list of all enrolled student_ids once, and the outer query returns every student whose student_id is absent from that list. This produces the exact same unenrolled students (Peter Audu, Maryam Tafawa, and Transfer Student) as Week 7's LEFT JOIN ... IS NULL query.

-- ============================================================
-- Task 5: Student(s) with highest enrolments per department (Correlated subquery)
-- ============================================================
SELECT d.dept_name, s.full_name,
       (SELECT COUNT(*) FROM Enrolment e WHERE e.student_id = s.student_id) AS courses
FROM Student s
JOIN Department d ON s.dept_id = d.dept_id
WHERE (SELECT COUNT(*) FROM Enrolment e WHERE e.student_id = s.student_id) = (
    SELECT MAX(dept_counts.cnt)
    FROM (
        SELECT s2.dept_id, COUNT(e2.course_id) AS cnt
        FROM Student s2
        LEFT JOIN Enrolment e2 ON s2.student_id = e2.student_id
        GROUP BY s2.student_id, s2.dept_id
    ) AS dept_counts
    WHERE dept_counts.dept_id = s.dept_id
)
ORDER BY d.dept_name ASC, s.full_name ASC;
-- Explanation: For each student row in the outer query, the correlated subquery computes the maximum enrolment count among all students belonging to that same department (dept_counts.dept_id = s.dept_id) and returns the student(s) matching that peak count, allowing ties.